-- Suivi multi-appareils et gestion des statuts des commandes existantes.
-- À exécuter après schema.sql dans Supabase Dashboard > SQL Editor.

create table if not exists public.suivi_commandes (
  id bigint generated by default as identity primary key,
  commande_id text not null references public.commandes(id) on delete cascade,
  status text not null check (status in (
    'Commande reçue - en attente de confirmation',
    'Confirmée',
    'En préparation',
    'Expédiée',
    'Livrée',
    'Annulée'
  )),
  created_at timestamptz not null default now()
);

create index if not exists suivi_commandes_commande_id_created_at_idx
  on public.suivi_commandes (commande_id, created_at desc, id desc);

alter table public.suivi_commandes enable row level security;

create or replace function public.initialiser_suivi_commande()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.suivi_commandes (commande_id, status)
  values (new.id, 'Commande reçue - en attente de confirmation');
  return new;
end;
$$;

revoke all on function public.initialiser_suivi_commande() from public, anon, authenticated;

drop trigger if exists commandes_initialiser_suivi on public.commandes;
create trigger commandes_initialiser_suivi
  after insert on public.commandes
  for each row execute function public.initialiser_suivi_commande();

create or replace function public.suivre_commande(p_id text, p_phone text)
returns table (id text, date text, status text)
language sql
stable
security definer
set search_path = ''
as $$
  select c.id, c.date,
    coalesce(s.status, 'Commande reçue - en attente de confirmation')
  from public.commandes as c
  left join lateral (
    select h.status, h.created_at
    from public.suivi_commandes as h
    where h.commande_id = c.id
    order by h.created_at desc, h.id desc
    limit 1
  ) as s on true
  where upper(btrim(c.id)) = upper(btrim(p_id))
    and regexp_replace(
          regexp_replace(coalesce(c.phone, ''), '[^0-9]', '', 'g'),
          '^(00213|213)', '0'
        ) = regexp_replace(
          regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g'),
          '^(00213|213)', '0'
        )
    and length(regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g')) >= 8
  limit 1;
$$;

revoke all on function public.suivre_commande(text, text) from public;
revoke all on function public.suivre_commande(text, text) from anon, authenticated;
grant execute on function public.suivre_commande(text, text) to anon, authenticated;

create or replace function public.admin_lister_commandes()
returns table (
  id text,
  date text,
  client text,
  phone text,
  wilaya text,
  total text,
  status text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'admin' then
    raise exception 'Accès administrateur requis' using errcode = '42501';
  end if;

  return query
  select c.id, c.date, c.client, c.phone, c.wilaya, c.total,
    coalesce(s.status, 'Commande reçue - en attente de confirmation')
  from public.commandes as c
  left join lateral (
    select h.status, h.created_at
    from public.suivi_commandes as h
    where h.commande_id = c.id
    order by h.created_at desc, h.id desc
    limit 1
  ) as s on true
  order by s.created_at desc nulls last, c.id desc
  limit 200;
end;
$$;

revoke all on function public.admin_lister_commandes() from public;
revoke all on function public.admin_lister_commandes() from anon, authenticated;
grant execute on function public.admin_lister_commandes() to authenticated;

create or replace function public.admin_modifier_statut_commande(p_id text, p_status text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'admin' then
    raise exception 'Accès administrateur requis' using errcode = '42501';
  end if;

  if p_status not in (
    'Commande reçue - en attente de confirmation',
    'Confirmée',
    'En préparation',
    'Expédiée',
    'Livrée',
    'Annulée'
  ) then
    raise exception 'Statut de commande invalide' using errcode = '22023';
  end if;

  if not exists (select 1 from public.commandes where id = p_id) then
    raise exception 'Commande introuvable' using errcode = 'P0002';
  end if;

  insert into public.suivi_commandes (commande_id, status)
  values (p_id, p_status);

  return true;
end;
$$;

revoke all on function public.admin_modifier_statut_commande(text, text) from public;
revoke all on function public.admin_modifier_statut_commande(text, text) from anon, authenticated;
grant execute on function public.admin_modifier_statut_commande(text, text) to authenticated;
